a <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (!length(a)) stop("Run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",a[1])))
item_name <- "Baldoni_etal_2025_Table2";root <- dirname(folder)
s <- utils::read.csv(file.path(folder,paste0(item_name,"_snapshot.csv")),check.names=FALSE,colClasses="character",fileEncoding="UTF-8")
stopifnot(nrow(s)==7L,ncol(s)==5L)
num <- function(x) as.numeric(gsub("−","-",x,fixed=TRUE))
out <- data.frame(source_row=seq_len(nrow(s)),metric_as_published=s[[1]],seasonal_change_estimate=num(s[[2]]),estimated_error=num(s[[3]]),lower_CI=num(s[[4]]),upper_CI=num(s[[5]]),comparison="winter minus summer",data_role="Bayesian seasonal model effect; not raw diffusion value",stringsAsFactors=FALSE)
stopifnot(!anyNA(out$seasonal_change_estimate),all(out$lower_CI<=out$seasonal_change_estimate & out$seasonal_change_estimate<=out$upper_CI))
utils::write.csv(out,file.path(folder,paste0(item_name,".csv")),row.names=FALSE,na="",fileEncoding="UTF-8")
reg <- readxl::read_excel(file.path(root,"__ReadMeAddON.xlsx"),sheet="Sheet1")
hit <- which(reg[["Item name"]]==item_name);if(length(hit)!=1L) stop("Expected one AddON registry row")
encoded <- as.character(reg[["Item encoded"]][hit])
utils::write.table(out,file.path(root,"__Public","comparative-data",paste0(encoded,".tsv")),sep="\t",row.names=FALSE,na="",fileEncoding="UTF-8")
cat(item_name,": ",nrow(out)," model effects\n",sep="")
