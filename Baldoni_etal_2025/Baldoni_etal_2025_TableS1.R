a <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (!length(a)) stop("Run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",a[1])))
item_name <- "Baldoni_etal_2025_TableS1"; root <- dirname(folder)
s <- readxl::read_excel(file.path(folder,paste0(item_name,"_snapshot.xlsx")),col_names=FALSE)
stopifnot(nrow(s)==98L,ncol(s)==6L)
v <- lapply(s,as.character)
header <- which(!is.na(v[[1]]) & v[[1]]!="Season interaction")
stopifnot(identical(header,c(1L,15L,29L,43L,57L,71L,85L)))
metric <- rep(NA_character_,nrow(s))
for (j in seq_along(header)) { end <- if (j==length(header)) nrow(s) else header[j+1L]-1L; metric[header[j]:end] <- v[[1]][header[j]] }
keep <- setdiff(seq_len(nrow(s)),header)
out <- data.frame(source_xlsx_row=keep,metric_as_published=metric[keep],effect_as_published=ifelse(is.na(v[[1]][keep]),"",v[[1]][keep]),brain_region_as_published=v[[2]][keep],estimate=as.numeric(v[[3]][keep]),estimated_error=as.numeric(v[[4]][keep]),lower_CI=as.numeric(v[[5]][keep]),upper_CI=as.numeric(v[[6]][keep]),observation_level="Bayesian model season interaction by region",data_role="model coefficient; not raw brain-region trait",stringsAsFactors=FALSE)
stopifnot(nrow(out)==91L,!anyNA(out$estimate),!anyNA(out$brain_region_as_published))
utils::write.csv(out,file.path(folder,paste0(item_name,".csv")),row.names=FALSE,na="",fileEncoding="UTF-8")
reg <- readxl::read_excel(file.path(root,"__ReadMeAddON.xlsx"),sheet="Sheet1")
hit <- which(reg[["Item name"]]==item_name);if(length(hit)!=1L) stop("Expected one AddON registry row")
encoded <- as.character(reg[["Item encoded"]][hit])
utils::write.table(out,file.path(root,"__Public","comparative-data",paste0(encoded,".tsv")),sep="\t",row.names=FALSE,na="",fileEncoding="UTF-8")
cat(item_name,": ",nrow(out)," model coefficients\n",sep="")
