a <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (!length(a)) stop("Run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",a[1])))
item_name <- "Baldoni_etal_2025_TableS4"; root <- dirname(folder)
s <- utils::read.csv(file.path(folder,paste0(item_name,"_snapshot.csv")),check.names=FALSE,colClasses="character")
stopifnot(nrow(s)==3L,ncol(s)==5L)
out <- data.frame(source_row=seq_len(nrow(s)),term_as_published=s[[1]],estimate=as.numeric(s[[2]]),estimated_error=as.numeric(s[[3]]),lower_CI_as_published=as.numeric(s[[4]]),upper_CI_as_published=as.numeric(s[[5]]),model_response="brain volume",data_role="Bayesian model coefficient; not raw trait measurement",source_note=ifelse(4L==3L & seq_len(nrow(s))==2L,"Source lower CI -.024 exceeds estimate -0.11; retained as printed; verify with authors before inferential use",""),stringsAsFactors=FALSE)
stopifnot(!anyNA(out$estimate),!anyNA(out$lower_CI_as_published))
utils::write.csv(out,file.path(folder,paste0(item_name,".csv")),row.names=FALSE,na="",fileEncoding="UTF-8")
reg <- readxl::read_excel(file.path(root,"__ReadMeAddON.xlsx"),sheet="Sheet1")
hit <- which(reg[["Item name"]]==item_name);if(length(hit)!=1L) stop("Expected one AddON registry row")
encoded <- as.character(reg[["Item encoded"]][hit])
utils::write.table(out,file.path(root,"__Public","comparative-data",paste0(encoded,".tsv")),sep="\t",row.names=FALSE,na="",fileEncoding="UTF-8")
cat(item_name,": ",nrow(out)," model coefficients\n",sep="")
