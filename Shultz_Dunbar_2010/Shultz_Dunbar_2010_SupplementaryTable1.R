# Rebuild the complete supplementary table, preserving blank counts and printed names.
a <- grep('^--file=', commandArgs(FALSE), value=TRUE)
if (length(a)!=1L) stop('Run with Rscript')
folder <- dirname(normalizePath(sub('^--file=', '', a)))
html <- tempfile(fileext='.html')
status <- system2('textutil', c('-convert','html','-output',shQuote(html),shQuote(file.path(folder,'Supplementary_Information_PS.doc'))))
if (status != 0L) stop('textutil failed')
if (!requireNamespace('xml2',quietly=TRUE)) stop('Install the xml2 R package')
doc <- xml2::read_html(html)
tables <- xml2::xml_find_all(doc,'.//table')
stopifnot(length(tables)==1L)
rows <- xml2::xml_find_all(tables[[1]],'./tr|./tbody/tr')
cells <- lapply(rows,function(r) trimws(gsub('\u00a0',' ',xml2::xml_text(xml2::xml_find_all(r,'./td|./th')))))
stopifnot(all(lengths(cells)==4L),identical(cells[[1]],c('Description','Species','Individuals','Study')))
d <- as.data.frame(do.call(rbind,cells[-1]),stringsAsFactors=FALSE)
names(d) <- c('description','species','individuals','study')
stopifnot(nrow(d)==121L,all(grepl('^[0-9]*$',d$individuals)))
d$individuals <- as.integer(d$individuals)
stopifnot(sum(is.na(d$individuals))==9L)
write.csv(d,file.path(folder,'Shultz_Dunbar_2010_SupplementaryTable1.csv'),row.names=FALSE,na='')
write.csv(d,file.path(folder,'Shultz_Dunbar_2010_TableS1.csv'),row.names=FALSE,na='')
tsv <- file.path(dirname(folder),'__Public','comparative-data')
if(dir.exists(tsv)) write.table(d,file.path(tsv,'10.1037%2Fa0018894_TableS1.tsv'),sep='\t',row.names=FALSE,na='',quote=FALSE)
unlink(html)
cat('Built all 121 printed study rows; 9 blank individual counts retained.\n')
