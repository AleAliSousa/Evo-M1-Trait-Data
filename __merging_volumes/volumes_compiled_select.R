if (do_hemisphere_reconciliation) {
  wide_v <- volumes_long %>% select(Species, Variable, Value) %>%
    pivot_wider(names_from = Variable, values_from = Value)
  mk <- function(stem) c(left = paste0(stem, "_left_Vol.mm3"),
                         right = paste0(stem, "_right_Vol.mm3"),
                         both = paste0(stem, "_Vol.mm3"))
  stems <- if (identical(bilateral_stems, "auto"))
             unique(sub("_(left|right)_Vol\\.mm3$", "",
                        grep("_(left|right)_Vol\\.mm3$", names(wide_v), value = TRUE)))
           else bilateral_stems
  stems <- setdiff(stems, bilateral_stems_exclude)
  message("Step 7 both-sides stems: ", paste(stems, collapse = ", "),
          if (length(bilateral_stems_exclude)) paste0(" | excluded: ",
              paste(bilateral_stems_exclude, collapse = ", ")) else "")
  unil_cols <- grep("_unilateral_Vol\\.mm3$", names(wide_v), value = TRUE)
  getcol <- function(nm) if (nm %in% names(wide_v)) wide_v[[nm]] else rep(NA_real_, nrow(wide_v))

  bilat <- list()
  for (st in stems) {                                        # left (+right) -> both
    m <- mk(st); L <- getcol(m["left"]); R <- getcol(m["right"])
    both <- ifelse(!is.na(L) & !is.na(R), L + R,
            ifelse(!is.na(L), 2*L, ifelse(!is.na(R), 2*R, NA_real_)))
    est  <- xor(!is.na(L), !is.na(R))                        # only one side present -> doubled
    src  <- ifelse(!is.na(L), m["left"], m["right"])
    k <- !is.na(both)
    bilat[[unname(m["both"])]] <- tibble(Species = wide_v$Species[k], Variable = unname(m["both"]),
                                         Value = both[k], est = est[k], src = src[k])
  }
  for (uv in unil_cols) {                                    # one side only -> 2x (flagged)
    bv <- sub("_unilateral_Vol\\.mm3$", "_Vol.mm3", uv); U <- getcol(uv); k <- !is.na(U)
    bilat[[bv]] <- tibble(Species = wide_v$Species[k], Variable = bv, Value = 2*U[k],
                          est = TRUE, src = uv)
  }
  bilat <- bind_rows(bilat)
  if (nrow(bilat)) {
    # a real both-sides value always beats a doubled estimate
    bilat <- bilat %>% anti_join(volumes_long %>% distinct(Species, Variable),
                                 by = c("Species","Variable"))
    # A derived both-sides value inherits the provenance of the one-side variable it was built from --
    # that is the paper a reader must cite for it, even though the arithmetic happened here.
    src_meta <- volumes_long %>% transmute(Species, src = Variable, Teams, n_teams,
                                           Sources, n_sources, Source_detail, Year_used)
    volumes_long <- bind_rows(volumes_long,
      bilat %>% left_join(src_meta, by = c("Species","src")) %>%
        transmute(Species, Variable, Value, Teams, n_teams,
                  Sources, n_sources, Source_detail, Year_used)) %>%
      arrange(Species, Variable)
    flags <- bind_rows(flags, bilat %>% filter(est) %>%
      transmute(Species, Variable, flag = "estimated_bilateral_from_unilateral",
                detail = paste0("both-hemisphere estimated as 2x ", src, " (only one side measured)")))
  }
}

## ---- 7b  Provenance for the OTHER kind of doubling --------------------------------------------
## Values whose PUBLISHED figure is already 2x one side. Not a veto -- the value is used exactly as
## published; this only records that the both-sides number is an author-side estimate rather than a
## both-sides measurement, so it is never doubled again and so anyone comparing it to a truly
## bilateral measurement knows what they are holding. Stamped on the values actually USED (teamres),
## joined by the winning source.
if (nrow(lat_src_doubled)) {
  # `tie_rule = "mean"` can write "A + B" into Source. Split on that separator and match EXACTLY:
  # item names here are prefix-nested (Stephan_etal_1981_TableI is a substring of ..._TableIII), so
  # substring matching would mis-attribute the moment a Stephan table is registered `by_source`.
  .doubled_ref <- function(variable, source) {
    refs <- lat_src_doubled$Reference[lat_src_doubled$Standardized_Term == variable]
    hit  <- intersect(refs, trimws(strsplit(source, "+", fixed = TRUE)[[1]]))
    if (length(hit)) paste(sort(hit), collapse = " + ") else NA_character_
  }
  pubdbl <- teamres %>%
    filter(Variable %in% lat_src_doubled$Standardized_Term) %>%
    # vapply, not mapply: mapply returns list() on zero rows, which makes .ref a list-column.
    mutate(.ref = vapply(seq_len(n()),
                         function(i) .doubled_ref(Variable[i], Source[i]), character(1))) %>%
    filter(!is.na(.ref)) %>%
    distinct(Species, Variable, .ref) %>%
    # A one-team selection needs no caveat, but step 6 averages across teams whenever the selection
    # names more than one -- and then the merged number is a mean the doubled source contributed to,
    # not itself 2x one hemisphere. Say which, so the flag can never overclaim. (Mirrors 7b in
    # volumes_compiled.R, which is always multi-team.)
    left_join(volumes_long %>% select(Species, Variable, Teams, n_teams),
              by = c("Species", "Variable")) %>%
    transmute(Species, Variable, flag = "published_bilateral_estimate",
              detail = ifelse(
                coalesce(n_teams, 1L) > 1L,
                paste0("a contributing source publishes its figure as 2x one hemisphere, doubled ",
                       "by the source (not by this merge): ", .ref, "; the merged value is the ",
                       "mean across ", n_teams, " teams (", Teams, ") -- see laterality_known.csv"),
                paste0("published value is 2x one hemisphere, doubled by the source (not by ",
                       "this merge): ", .ref, " -- see laterality_known.csv")))
  flags <- bind_rows(flags, pubdbl)
}

