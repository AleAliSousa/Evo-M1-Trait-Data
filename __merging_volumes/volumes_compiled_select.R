# SELECT merge — compile brain-structure VOLUMES from a HAND-CHOSEN subset of tables.
# Sibling of volumes_compiled.R (canonical core collection) and volumes_compiled_DeCasien.R (DeCasien subset).
# Same engine; what differs is (a) the selection block below, (b) the output suffix, and (c) an
# explicit, hand-editable VALUE-FLAG registry that can veto a value even when it is the most recent.
#
# WHY THIS SCRIPT EXISTS
#   volumes_compiled.R merges everything and splits sources into Tier 1 (Stephan collection, most
#   recent wins) and Tier 2 (independent series, cross-team averaged). Sometimes you want the
#   opposite: a small, deliberately chosen set of tables treated as ONE evolving dataset, where the
#   most recent measurement of each (species x structure) supersedes the older ones — except where
#   you have decided a particular value must not be used, however recent it is.
#
# THE RULE IMPLEMENTED HERE
#   1. Every table in `select_datasets` is collapsed to ONE value per species x structure
#      (per-specimen tables are averaged within the table first).
#   2. Candidates are then resolved WITHIN each team by MOST RECENT `year`; ties broken by
#      `tie_rule`.
#   3. A candidate whose (Source, Species, Variable) matches a `skip` row in
#      volumes_select_value_flags.csv is REMOVED BEFORE the recency pick, so the next-most-recent
#      unflagged value wins instead. Every such skip is written to the generated README and to
#      volumes_select_flagged_not_used.csv.
#   4. If the selection names more than one team, the surviving per-team values are AVERAGED across
#      teams exactly as in volumes_compiled.R. With a single team (the default) this is a no-op.
#   5. Body/brain mass follow `mass_rule` (default: pinned to the Stephan 1981 reference tables,
#      as in volumes_compiled.R; set to "recent" to treat mass like any other variable).
#   6. Step 7 hemisphere reconciliation is unchanged: one-side volumes get a both-sides partner
#      (left + right where both exist, otherwise 2x with a flag).
#
# TO CHANGE THE SELECTION: edit `select_datasets` only. Everything downstream adapts. A table needs
# (i) a row in __ReadMe.xlsx (or an `enc_override` entry) so its TSV can be found, and (ii) a term
# map — either rows in standardized_term_volumes.csv or a per-reference file in
# standardized_term_by_reference/ (this script falls back to the per-reference file automatically).
#
# See README__volumes_compiled_select.md (regenerated by this script on every run).

