is_mass <- function(v) v %in% c("Body_Mass.g","Brain_Mass.mg")

## ============================================================================================
## 5a  Collapse each SOURCE to one value per species x structure
## ============================================================================================
## Per-specimen tables (de Sousa 2010) and tables that list the same species twice are averaged
## WITHIN the source first, so the recency comparison in 5b is table-vs-table, never row-vs-row.
cand <- long %>%
  group_by(Species, Variable, Source, Team, Year, Pick) %>%
  summarise(Value = mean(Value, na.rm = TRUE), n_obs = n(), .groups = "drop")

## ============================================================================================
## 5b  Value flags — a `skip` removes a candidate BEFORE the recency pick
## ============================================================================================
## Registry columns: Source, Species, Variable, flag, action, reason, evidence.
##   Source / Species / Variable : exact value, "*" (or blank) for all, or a trailing-"*" prefix
##                                 match, e.g. "Area_striata_*".
##   action : skip   = never use this value, however recent (reported in the README)
##            review = use it, but list it in the README as needing eyes
##            keep   = explicitly un-skip (use to carve an exception out of a broader skip row)
## The MOST SPECIFIC matching row wins (Source > Species > Variable); among equally specific rows
## the one LAST in the file wins. Edit the CSV, not this script.
vflags <- if (file.exists(flags_file)) {
  read.csv(flags_file, stringsAsFactors = FALSE, na.strings = c("NA",""), fileEncoding = "UTF-8")
} else {
  message("No ", flags_file, " -> no value flags applied.")
  data.frame(Source=character(), Species=character(), Variable=character(),
             flag=character(), action=character(), reason=character(), evidence=character())
}
for (cl in c("Source","Species","Variable","flag","action","reason","evidence"))
  if (is.null(vflags[[cl]])) vflags[[cl]] <- NA_character_
vflags <- vflags %>%
  mutate(across(c(Source, Species, Variable), ~ ifelse(is.na(.x) | !nzchar(trimws(.x)), "*", trimws(.x))),
         action = tolower(ifelse(is.na(action) | !nzchar(trimws(action)), "review", trimws(action))),
         .row = row_number())
bad_action <- setdiff(vflags$action, c("skip","review","keep"))
if (length(bad_action))
  stop(flags_file, ": unknown action(s) ", paste(unique(bad_action), collapse=", "),
       " — use skip / review / keep.", call. = FALSE)

.pat_match <- function(pat, x) {
  if (pat == "*") return(rep(TRUE, length(x)))
  if (grepl("\\*$", pat)) return(startsWith(x, sub("\\*$", "", pat)))
  x == pat
}
cand$flag <- NA_character_; cand$action <- "use"; cand$flag_reason <- NA_character_
cand$flag_evidence <- NA_character_; cand$.spec <- -1L; cand$.row <- NA_integer_
vflags$hits <- 0L
for (i in seq_len(nrow(vflags))) {
  f <- vflags[i, ]
  hit <- .pat_match(f$Source, cand$Source) & .pat_match(f$Species, cand$Species) &
         .pat_match(f$Variable, cand$Variable)
  vflags$hits[i] <- sum(hit)
  spec <- 4L*(f$Source != "*") + 2L*(f$Species != "*") + 1L*(f$Variable != "*")
  take <- hit & (spec >= cand$.spec)          # >= so a later, equally specific row wins
  cand$flag[take] <- f$flag; cand$action[take] <- f$action
  cand$flag_reason[take] <- f$reason; cand$flag_evidence[take] <- f$evidence
  cand$.spec[take] <- spec; cand$.row[take] <- f$.row
}
cand$action[cand$action == "keep"] <- "use"    # `keep` = an explicit un-skip
stale <- vflags %>% filter(hits == 0)
if (nrow(stale))
  message("Value-flag registry: ", nrow(stale), " row(s) matched nothing in this selection ",
          "(listed in the README as stale).")

## ============================================================================================
## 5c  Resolve WITHIN each team: most recent unflagged value wins
## ============================================================================================
usable <- cand %>% filter(action != "skip") %>%
  mutate(.tiekey = if (tie_rule == "last") -Pick else Pick)
teamres <- usable %>%
  arrange(Species, Variable, Team, desc(Year), .tiekey) %>%   # newest first, tie-break by `pick`
  group_by(Species, Variable, Team) %>%
  mutate(.top = Year == first(Year)) %>%                      # the newest year's row(s)
  summarise(n_tied = sum(.top),
            Value  = if (tie_rule == "mean" && sum(.top) > 1) mean(Value[.top]) else first(Value),
