a <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (!length(a)) stop("Run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",a[1])))
item_name <- "deRooij_etal_2016_Table3"; root <- dirname(folder)
s <- utils::read.csv(file.path(folder,paste0(item_name,"_snapshot.csv")),skip=2,nrows=3,
                     check.names=FALSE,colClasses="character",fileEncoding="UTF-8")
names(s) <- c("measure_as_published","n","born_before","in_early_gestation","conceived_after","total_as_published","P")
stopifnot(nrow(s)==3L,ncol(s)==7L,identical(s$n,c("118","118","116")))
unit_as_published <- c("dimensionless", "×10³ mm²/s", "ml")
summary_type <- c("arithmetic mean (SD)", "arithmetic mean (SD)", "geometric mean (geometric SD)")
groups <- c("born_before","in_early_gestation","conceived_after","total")
out <- do.call(rbind,lapply(seq_len(nrow(s)),function(i) {
 vals <- c(s$born_before[i],s$in_early_gestation[i],s$conceived_after[i],sub(" .*","",s$total_as_published[i]))
 sd <- rep(NA_real_,4L); sd[4] <- as.numeric(sub(".*\\(([^)]+)\\).*","\\1",s$total_as_published[i]))
 data.frame(source_row=i+3L,measure_as_published=s$measure_as_published[i],exposure_group=groups,n=as.integer(s$n[i]),value_as_published=as.numeric(vals),total_SD_as_published=sd,summary_type=summary_type[i],unit_as_published=unit_as_published[i],P_exposed_vs_combined_unexposed=as.numeric(s$P[i]),source_note=ifelse(i==3L,"Printed WMH values are 2969/2796/2552/2757 ml; apparent magnitude anomaly, retained as published; do not pool pending source clarification", ""),stringsAsFactors=FALSE)
}))
stopifnot(nrow(out)==12L,!anyNA(out$value_as_published),!anyNA(out$P_exposed_vs_combined_unexposed))
utils::write.csv(out,file.path(folder,paste0(item_name,".csv")),row.names=FALSE,na="",fileEncoding="UTF-8")
reg <- readxl::read_excel(file.path(root,"__ReadMe.xlsx"),sheet="Sheet1")
hit <- which(reg[["Item name"]]==item_name)
if (length(hit)!=1L) stop("Expected one registry row")
encoded <- as.character(reg[["Item encoded"]][hit])
utils::write.table(out,file.path(root,"__Public","comparative-data",paste0(encoded,".tsv")),sep="\t",row.names=FALSE,na="",fileEncoding="UTF-8")
cat(item_name,": ",nrow(out)," group-by-measure rows\n",sep="")
